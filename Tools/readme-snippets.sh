#!/bin/sh
# Copies every ```swift block in README.md into Examples/ReadmeSnippets.swift,
# and every block in the DocC articles into Examples/DocCSnippets.swift, one
# function per block, so the Examples target compiles the documentation.
#
#   Tools/readme-snippets.sh          regenerate both files
#   Tools/readme-snippets.sh --check  fail if either file is out of date (CI)
#
# A block that is not Swift you can compile (Package.swift, say) opts out with
# `<!-- readme-snippets: skip -->` on the line before its fence.
#
# `<!-- readme-snippet: name -->` on the line before a fence names the block:
# its function is `readmeSnippet_name()` instead of a numbered one, so code
# that runs a snippet (Tools/ReadmeMedia renders the README's GIFs) can call it
# by name and survive blocks being added or reordered.
#
# Placeholder values the snippets use (URLs, images) live in
# Examples/ReadmeSnippetAssets.swift.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
docc="$root/Sources/Kadr/Kadr.docc"

# header SOURCE [IMPORT...]: the file comment and imports. Snippets' own
# import lines are dropped, so a module a snippet needs is named here.
header() {
    echo "// Generated by Tools/readme-snippets.sh from $1. Do not edit:"
    echo "// change the source and run the script again."
    echo ""
    shift
    for module in AVFoundation CoreImage Foundation Kadr "$@"; do
        echo "import $module"
    done | sort
}

# blocks FILE LABEL PREFIX: one function per ```swift block in FILE, named
# PREFIX1, PREFIX2, ... and commented with LABEL:line.
blocks() {
    awk -v label="$2" -v prefix="$3" '
    BEGIN { n = 0; nlets = 0; inblock = 0; skip = 0; dropped = 0; prev = "" }
    !inblock && /^```swift[ \t]*$/ {
        inblock = 1
        skip = (prev ~ /<!-- readme-snippets: skip -->/)
        if (!skip) {
            n++
            name = n ""
            if (match(prev, /<!-- readme-snippet: [A-Za-z][A-Za-z0-9]* -->/)) {
                name = "_" substr(prev, RSTART + 21, RLENGTH - 25)
            }
            print ""
            printf "// %s:%d\n", label, NR
            printf "func %s%s() async throws {\n", prefix, name
        }
        next
    }
    inblock && /^```[ \t]*$/ {
        inblock = 0
        if (!skip) {
            # A snippet ends on `let url = try await ...` and never reads it.
            # Using each top-level constant keeps the build free of warnings.
            for (i = 1; i <= nlets; i++) printf "    _ = %s\n", lets[i]
            print "}"
        }
        nlets = 0; prev = ""
        next
    }
    inblock {
        if (skip) next
        if ($0 ~ /^import /) { dropped = 1; next }
        # The blank line after a dropped import would open the body.
        if (dropped && $0 ~ /^[ \t]*$/) { dropped = 0; next }
        dropped = 0
        if (match($0, /^let [A-Za-z_][A-Za-z0-9_]*/)) lets[++nlets] = substr($0, 5, RLENGTH - 4)
        if ($0 ~ /^[ \t]*$/) print ""; else print "    " $0
        next
    }
    /[^ \t]/ { prev = $0 }
    END {
        if (inblock) { print "unterminated ```swift block in " label > "/dev/stderr"; exit 1 }
    }
    ' "$1"
}

readme() {
    header README.md
    blocks "$root/README.md" README.md readmeSnippet
}

# Articles are taken in name order so the output is stable. Each article's
# functions are prefixed with its name: doccSnippet_Slideshows_1, ...
articles() {
    header "the DocC articles in Sources/Kadr/Kadr.docc" AVKit SwiftUI
    for article in "$docc"/*.md; do
        name=$(basename "$article" .md)
        blocks "$article" "Kadr.docc/$name.md" "doccSnippet_${name}_"
    done
}

status=0
for target in readme:Examples/ReadmeSnippets.swift articles:Examples/DocCSnippets.swift; do
    generator=${target%%:*}
    out="$root/${target#*:}"
    if [ "${1:-}" = "--check" ]; then
        if ! "$generator" | diff -u "$out" - ; then
            echo "${target#*:} is out of date. Run Tools/readme-snippets.sh." >&2
            status=1
        fi
    else
        "$generator" > "$out"
    fi
done
exit $status
